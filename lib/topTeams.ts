// Normalize a metro name into a stable token so dataset names can match
// sheet/essay names regardless of accents and punctuation. Mirrors
// normalizeMetroName() in lib/neighborhoods.ts so the two reference modules
// behave the same.
export function normalizeTopTeamMetroName(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[.'\u2019]/g, "")
    .replace(/[\s_/]+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

export function topTeamAnchorId(metro: string): string {
  return "team-" + normalizeTopTeamMetroName(metro);
}

// Aliases for metros where the dataset name and the sheet name diverge.
// Keyed on the normalized dataset name; value is the normalized sheet name.
const METRO_NAME_ALIASES: Record<string, string> = {
  // Dataset uses bare "Minho"; sheet uses "Minho (Braga)". Map dataset->sheet
  // so the metro page lookup hits the row.
  minho: "minho-braga",
};

/**
 * Look up the top-team pick for a dataset metro by name. Returns null when
 * the metro has no entry on the Top Sports Teams sheet. Match is tolerant of
 * accent and punctuation differences and falls back through METRO_NAME_ALIASES
 * for the rare cases where the two name forms diverge.
 */
export function getTopTeamByMetroName(metroName: string): TopTeamPick | null {
  const target = normalizeTopTeamMetroName(metroName);
  const alias = METRO_NAME_ALIASES[target] ?? target;
  for (const t of TOP_TEAMS) {
    const candidate = normalizeTopTeamMetroName(t.metro);
    if (candidate === target || candidate === alias) return t;
  }
  return null;
}


/**
 * Reverse-lookup: find the Top Team entry that names this franchise, even
 * if the picking metro differs from the franchise's own metro. This is
 * load-bearing for cases like the Green Bay Packers, who are listed as
 * Milwaukee's Top Team (rank 159) despite playing in Green Bay. The
 * franchise's own metro lookup misses; this team-name lookup catches it.
 *
 * Tie-break: if the franchise IS the named pick for multiple metros
 * (rare), prefer the entry whose metro matches the franchise's own metro
 * so the badge reads naturally. Otherwise return the first match.
 *
 * Pass an array of candidate names (display_name, city + team, just team)
 * to be tolerant of NFL\u2019s "{city} {team}" form vs MLB\u2019s bare
 * "{team}" form. Pass the franchise\u2019s own metro as ownMetro so the
 * tie-break works.
 */
export function findTopTeamForName(
  candidateNames: ReadonlyArray<string | null | undefined>,
  ownMetro?: string,
): TopTeamPick | null {
  const norm = normalizeTopTeamMetroName;
  const normalizedTargets = new Set(
    candidateNames
      .filter((n): n is string => typeof n === "string" && n.length > 0)
      .map(norm)
      .filter((n) => n.length > 0),
  );
  if (normalizedTargets.size === 0) return null;
  const ownMetroNorm = ownMetro ? norm(ownMetro) : "";
  let firstMatch: TopTeamPick | null = null;
  for (const t of TOP_TEAMS) {
    const teamCandidates = t.team.split("/").map((p) => norm(p.trim()));
    const hit = teamCandidates.some((c) => normalizedTargets.has(c));
    if (!hit) continue;
    if (!firstMatch) firstMatch = t;
    if (ownMetroNorm && norm(t.metro) === ownMetroNorm) return t;
  }
  return firstMatch;
}
